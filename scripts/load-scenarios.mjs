import { readFileSync, writeFileSync } from "node:fs";
import { loadScenarios } from "./scenario-lib.mjs";

// Compiles reviewed JSON into an idempotent Supabase migration. Applying the migration
// remains the deployment step; no production credential is needed to review the content.
const check = process.argv.includes("--check");
const output = process.argv.find((arg, index) => index > 1 && arg !== "--check") ?? "supabase/migrations/20261016010000_scenario_seeds.sql";
const { catalogue, scenarios } = loadScenarios();
const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const arr = (values) => `array[${values.map(q).join(",")}]::text[]`;
const lines = ["-- Generated by node scripts/load-scenarios.mjs. Do not hand edit."];
for (const course of catalogue.courses) {
  lines.push(`insert into public.arena_courses(id,slug,title) values(${q(course.slug)},${q(course.slug)},${q(course.title)}) on conflict(id) do update set title=excluded.title;`);
  for (const c of course.concepts) {
    const id = `${course.slug}:${c.id}`;
    lines.push(`insert into public.arena_concepts(id,course_id,name,tier,prerequisite_concept_ids) values(${q(id)},${q(course.slug)},${q(c.name)},${q(c.tier)},${arr(c.prerequisite_concept_ids.map((x) => `${course.slug}:${x}`))}) on conflict(id) do update set name=excluded.name,tier=excluded.tier,prerequisite_concept_ids=excluded.prerequisite_concept_ids;`);
  }
}
for (const s of scenarios) {
  const id = `${s.course_slug}:${s.slug}`;
  const ids = (values) => arr(values.map((x) => `${s.course_slug}:${x}`));
  lines.push(`insert into public.arena_scenarios(id,course_id,slug,title,hook,context,tier,concept_ids,estimated_minutes,status,solution_brief) values(${q(id)},${q(s.course_slug)},${q(s.slug)},${q(s.title)},${q(s.hook)},${q(s.context)},${q(s.tier)},${ids(s.concept_ids)},${s.estimated_minutes},${q(s.status)},${q(s.solution_brief)}) on conflict(id) do update set title=excluded.title,hook=excluded.hook,context=excluded.context,tier=excluded.tier,concept_ids=excluded.concept_ids,estimated_minutes=excluded.estimated_minutes,status=excluded.status,solution_brief=excluded.solution_brief;`);
  s.steps.forEach((step, index) => {
    const sid = `${id}:${index + 1}`;
    lines.push(`insert into public.arena_scenario_steps(id,scenario_id,position,kind,step_type,prompt,context_note,options,correct_option_id,explanation,bottleneck_note,concept_ids,code_snippet,language) values(${q(sid)},${q(id)},${index + 1},${q(step.kind)},${q(step.step_type)},${q(step.prompt)},${step.context_note ? q(step.context_note) : "null"},${q(JSON.stringify(step.options))}::jsonb,${q(step.correct_option_id)},${q(step.explanation)},${q(step.bottleneck_note)},${ids(step.concept_ids)},${step.code_snippet ? q(step.code_snippet) : "null"},${step.language ? q(step.language) : "null"}) on conflict(id) do update set prompt=excluded.prompt,context_note=excluded.context_note,options=excluded.options,correct_option_id=excluded.correct_option_id,explanation=excluded.explanation,bottleneck_note=excluded.bottleneck_note,concept_ids=excluded.concept_ids,code_snippet=excluded.code_snippet,language=excluded.language;`);
  });
}
const sql = `${lines.join("\n")}\n`;
if (check) {
  if (readFileSync(output, "utf8") !== sql) throw new Error(`${output} is stale; run node scripts/load-scenarios.mjs`);
  console.log(`Validated ${scenarios.length} scenarios; seed migration is current.`);
} else {
  writeFileSync(output, sql);
  console.log(`Validated ${scenarios.length} scenarios; wrote ${output}`);
}
